import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { OperationError } from './context.js';
import { writeRepoFile } from './files.js';
import { adminRoute } from './generate.js';
import { configSchema, type Competitor, type Framework, type MainConfig } from './schema.js';

export * from './schema.js';

export const CONFIG_FILE = 'config/main-config.json';

export interface DerivedConfig {
  domain: string;
  enableHttps: 'true' | 'false';
  username: string;
  password: string;
  modules: string[];
  competitors: Competitor[];
  frameworks: Framework[];
  entrypoint: 'websecure' | 'web';
  protocol: 'https' | 'http';
  registryPort: '443' | '5000';
  /** Traefik certificate resolver for every HTTPS router; empty = the built-in default certificate. */
  certResolver: 'letsencrypt' | '';
  acmeEmail: string;
}

export function readConfig(repoDir: string): MainConfig {
  const file = path.join(repoDir, CONFIG_FILE);
  let raw: unknown;
  try {
    raw = JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (err) {
    throw new OperationError(`Could not read ${CONFIG_FILE}: ${(err as Error).message}`);
  }
  const parsed = configSchema.safeParse(raw);
  if (!parsed.success) {
    throw new OperationError(`Invalid ${CONFIG_FILE}: ${parsed.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`).join('; ')}`);
  }
  return parsed.data;
}

/**
 * Writes via a temp file + rename, so a reader never sees a half-written file.
 * World-readable like the git checkout it replaces.
 */
export function writeConfig(repoDir: string, config: MainConfig): void {
  const file = path.join(repoDir, CONFIG_FILE);
  const tmp = `${file}.${process.pid}.tmp`;
  writeRepoFile(repoDir, tmp, `${JSON.stringify(config, null, 2)}\n`, 0o644);
  fs.renameSync(tmp, file);
}

export function deriveConfig(config: MainConfig): DerivedConfig {
  const https = config.enableHttps === true || config.enableHttps === 'true';
  return {
    domain: config.domain,
    enableHttps: https ? 'true' : 'false',
    username: config.username,
    password: config.password,
    modules: config.modules,
    competitors: config.competitors,
    frameworks: config.frameworks,
    entrypoint: https ? 'websecure' : 'web',
    protocol: https ? 'https' : 'http',
    registryPort: https ? '443' : '5000',
    certResolver: https && config.letsencrypt ? 'letsencrypt' : '',
    acmeEmail: config.acmeEmail ?? '',
  };
}

/**
 * Variables the compose files interpolate for routing and TLS. The same set has to reach every `up` of
 * traefik.yaml (install.sh, init, start), otherwise compose recreates Traefik with a different command.
 */
export function routingEnv(cfg: DerivedConfig): Record<string, string> {
  return {
    GITEA_HOSTNAME: cfg.domain,
    REGISTRY_PORT: cfg.registryPort,
    CERT_RESOLVER: cfg.certResolver,
    ACME_EMAIL: cfg.acmeEmail,
    // Optional staging CA, from the infra repo's .admin.env (install.sh reads the same value)
    ACME_CA_SERVER: process.env.ACME_CA_SERVER ?? '',
  };
}

export function loadConfig(repoDir: string): DerivedConfig {
  return deriveConfig(readConfig(repoDir));
}

const PULLDECK_ENV = 'pulldeck.env';

function readEnvFile(file: string): Map<string, string> {
  let contents = '';
  try {
    contents = fs.readFileSync(file, 'utf8');
  } catch {
    // missing file = empty
  }
  const entries = new Map<string, string>();
  for (const line of contents.split(/\r?\n/)) {
    const eq = line.indexOf('=');
    if (eq > 0 && !line.startsWith('#')) entries.set(line.slice(0, eq), line.slice(eq + 1).trim());
  }
  return entries;
}

// Pulldeck is served at clara.<domain> (see pulldeck.yaml) and checks AUTH_TOKEN from pulldeck.env
export function readPulldeckToken(repoDir: string): string {
  const token = readEnvFile(path.join(repoDir, PULLDECK_ENV)).get('AUTH_TOKEN');
  if (!token) throw new OperationError(`AUTH_TOKEN not found in ${PULLDECK_ENV}; it is generated by init, run that first.`);
  return token;
}

/**
 * Writes pulldeck.env, read only by pulldeck: keeps AUTH_TOKEN (generated by the first init) and takes the registry
 * credentials from the root user, so a password changed in main-config.json reaches pulldeck on the next init.
 */
export function writePulldeckEnv(repoDir: string, cfg: DerivedConfig): string {
  const file = path.join(repoDir, PULLDECK_ENV);
  const env = readEnvFile(file);
  if (!env.get('AUTH_TOKEN')) env.set('AUTH_TOKEN', crypto.randomBytes(24).toString('base64url'));
  env.set('DOCKER_MANAGER_RUNNING_IN_CONTAINER', 'true');
  env.set('DOCKER_USERNAME', cfg.username);
  env.set('DOCKER_PASSWORD', cfg.password);
  writeRepoFile(repoDir, file, [...env].map(([k, v]) => `${k}=${v}`).join('\n') + '\n', 0o600);
  return env.get('AUTH_TOKEN')!;
}

export const ADMIN_ROUTE = 'config/traefik/admin.yaml';

/** Writes the admin UI's own Traefik route (see adminRoute); skipped while the Traefik config dir is missing. */
export function writeAdminRoute(repoDir: string, cfg: DerivedConfig = loadConfig(repoDir)): void {
  const file = path.join(repoDir, ADMIN_ROUTE);
  if (!fs.existsSync(path.dirname(file))) return;
  const content = adminRoute(cfg);
  try {
    if (fs.readFileSync(file, 'utf8') === content) return;
  } catch {
    // written below
  }
  writeRepoFile(repoDir, file, content);
}
