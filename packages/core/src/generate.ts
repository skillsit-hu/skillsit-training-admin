import type { DerivedConfig } from './config.js';
import { competitorHost } from './schema.js';

export function competitorService(cfg: DerivedConfig, user: string, module: string): string {
  const id = `${user}_${module}`;
  return `  ${id}:
    image: git.${cfg.domain}/${user}/${module}:latest
    container_name: ${id}
    restart: always
    networks:
      - gitea
    labels:
      - "traefik.enable=true"
      - "traefik.http.routers.${id}.rule=Host(\`${competitorHost(user, module, cfg.domain)}\`)"
      - "traefik.http.routers.${id}.entrypoints=${cfg.entrypoint}"
      - "traefik.http.routers.${id}.tls=${cfg.enableHttps}"
      - "traefik.http.routers.${id}.tls.certresolver=${cfg.certResolver}"
      - "traefik.http.services.${id}.loadbalancer.server.port=80"
`;
}

export function competitorSql(user: string, pass: string, module: string): string {
  return `  CREATE DATABASE IF NOT EXISTS \`${user}_${module}\`;
  CREATE USER IF NOT EXISTS '${user}'@'%' IDENTIFIED BY '${pass}';
  GRANT ALL PRIVILEGES ON *.* TO '${user}'@'%';
`;
}

/** The SQL create_user appends for a competitor added to a running environment. */
export function newUserSql(user: string, pass: string): string {
  return `CREATE USER IF NOT EXISTS '${user}'@'%' IDENTIFIED BY '${pass}';\nGRANT ALL PRIVILEGES ON *.* TO '${user}'@'%';\n`;
}

export function competitorsYaml(cfg: DerivedConfig): string {
  let services = '';
  for (const { username } of cfg.competitors) {
    for (const module of cfg.modules) services += competitorService(cfg, username, module);
  }
  return `services:\n${services}\nnetworks:\n  gitea:\n    external: true\n`;
}

export function competitorsSql(cfg: DerivedConfig): string {
  let sql = '';
  for (const { username, password } of cfg.competitors) {
    for (const module of cfg.modules) sql += competitorSql(username, password, module);
  }
  return sql;
}

/** A competitor repository found in Gitea by syncCompetitors (ported from infra-updater). */
export interface CompetitorRepo {
  owner: string;
  repo: string;
}

/** Container (and compose service) name of a competitor repository. */
export function competitorContainer({ owner, repo }: CompetitorRepo): string {
  return `${owner}_${repo}`;
}

export function competitorImage(domain: string, { owner, repo }: CompetitorRepo): string {
  return `git.${domain}/${owner}/${repo}`.toLowerCase();
}

/**
 * competitors.yaml as syncCompetitors writes it: one service per repository. No Traefik labels; the routes are in
 * competitorRoutes(), and Sablier starts the containers on the first request.
 */
export function syncedCompetitorsYaml(domain: string, repos: CompetitorRepo[]): string {
  let services = '';
  for (const r of repos) {
    const name = competitorContainer(r);
    services += `  ${name}:
    image: ${competitorImage(domain, r)}:latest
    container_name: ${name}
    restart: always
    networks:
      - gitea
    labels:
      - "sablier.enable=true"
      - "sablier.group=${name}"
`;
  }
  return `services:\n${services}\nnetworks:\n  gitea:\n    external: true\n`;
}

/**
 * Traefik dynamic config (config/traefik/competitors.yaml) for the competitor repositories: a Sablier middleware,
 * a router and a service each. Written as JSON, which is valid YAML. Traefik rejects empty sections and then drops
 * every file in the directory, including the default certificate, so no repositories means an empty file.
 */
export function competitorRoutes(cfg: DerivedConfig, repos: CompetitorRepo[]): string {
  if (repos.length === 0) return '';
  const middlewares: Record<string, unknown> = {};
  const routers: Record<string, unknown> = {};
  const services: Record<string, unknown> = {};
  for (const r of repos) {
    const name = competitorContainer(r);
    middlewares[`sablier-${name}`] = {
      plugin: { sablier: { group: name, dynamic: { displayName: name }, sablierUrl: 'http://sablier:10000' } },
    };
    routers[name] = {
      rule: `Host(\`${competitorHost(r.owner, r.repo, cfg.domain)}\`)`,
      entryPoints: ['websecure'],
      middlewares: [`sablier-${name}@file`],
      tls: cfg.certResolver ? { certResolver: cfg.certResolver } : {},
      service: name,
    };
    services[name] = { loadBalancer: { servers: [{ url: `http://${name}:80` }] } };
  }
  return `# Generated by syncCompetitors (skillsit-training-admin)\n${JSON.stringify({ http: { middlewares, routers, services } }, null, 2)}\n`;
}

/**
 * Traefik dynamic config for the admin UI itself (config/traefik/admin.yaml). The admin writes it from
 * main-config.json, so a changed domain or Let's Encrypt setting applies at once. Compose labels on admin.yaml
 * would only change when install.sh recreates the container; the admin cannot recreate itself.
 */
export function adminRoute(cfg: DerivedConfig): string {
  const route = {
    http: {
      routers: {
        'infra-admin': {
          rule: `Host(\`admin.${cfg.domain}\`)`,
          entryPoints: ['websecure'],
          tls: cfg.certResolver ? { certResolver: cfg.certResolver } : {},
          service: 'infra-admin',
        },
      },
      services: { 'infra-admin': { loadBalancer: { servers: [{ url: 'http://infra-admin:8090' }] } } },
    },
  };
  return `# Generated by the admin UI from config/main-config.json\n${JSON.stringify(route, null, 2)}\n`;
}

export function dotEnv(env: Record<string, string>): string {
  return Object.entries(env).map(([k, v]) => `${k}="${v}"`).join('\n') + '\n';
}
